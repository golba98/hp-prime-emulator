pub fn service_name(id: u32) -> Option<&'static str> {
    let idx = id.checked_sub(FIRST_SERVICE_ID)? as usize;
    SERVICE_NAMES.get(idx).copied().flatten()
}

/// Reverse lookup by verified name. Panics never; returns None if unknown.
pub fn service_id_by_name(name: &str) -> Option<u32> {
    let idx = SERVICE_NAMES.iter().position(|n| *n == Some(name))?;
    Some(FIRST_SERVICE_ID + idx as u32)
}
