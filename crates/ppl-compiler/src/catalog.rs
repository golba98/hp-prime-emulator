//! Documented HP Prime commands that this emulator does not implement.
//!
//! Generated from the command headings and syntax lines of chapters 23–29
//! ("Functions and commands" to "Programming in HP PPL") of the
//! *HP Prime Graphing Calculator User Guide*, Third Edition, December 2017
//! (HP part number 813269-003), minus every name the builtin table in
//! [`crate::builtins`] implements and the PPL keywords.
//!
//! The catalog exists so that valid calculator programs are never rejected
//! just because the emulator lacks a command: a call to one of these names
//! compiles, produces a compatibility warning, and raises an "unsupported"
//! runtime error only if it actually executes. Names are kept in their
//! documented spelling (CAS commands are lower case, Home and app commands
//! upper or mixed case). No argument counts are recorded, because none are
//! enforced: the emulator has no evidence for them.
//!
//! Regenerate (or extend) only from HP documentation, never by guessing.

/// Which subsystem a catalog command belongs to on the calculator.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CatalogKind {
    /// Home / program command or app function (upper or mixed case).
    Command,
    /// CAS command (lower case on the calculator).
    Cas,
}

impl CatalogKind {
    pub fn label(self) -> &'static str {
        match self {
            CatalogKind::Command => "command",
            CatalogKind::Cas => "CAS command",
        }
    }
}

/// A documented command the emulator does not implement.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct CatalogEntry {
    pub name: &'static str,
    pub kind: CatalogKind,
}

