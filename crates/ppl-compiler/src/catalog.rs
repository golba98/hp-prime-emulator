fn entry(name: &'static str) -> CatalogEntry {
    let kind = if name.starts_with(|c: char| c.is_lowercase()) {
        CatalogKind::Cas
    } else {
        CatalogKind::Command
    };
    CatalogEntry { name, kind }
}

/// Exact-spelling lookup.
pub fn lookup(name: &str) -> Option<CatalogEntry> {
    NAMES.binary_search(&name).ok().map(|i| entry(NAMES[i]))
}

/// Case-insensitive lookup, for spellings that differ from the
/// documentation only in case. Whether the calculator accepts such a
/// spelling is not verified, so callers should say so.
pub fn lookup_case_insensitive(name: &str) -> Option<CatalogEntry> {
    lookup(name).or_else(|| {
        NAMES
            .iter()
            .find(|n| n.eq_ignore_ascii_case(name))
            .map(|n| entry(n))
    })
}

/// Every catalog entry, for completion lists and documentation.
pub fn entries() -> impl Iterator<Item = CatalogEntry> {
    NAMES.iter().map(|n| entry(n))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn sorted_unique_and_disjoint_from_builtins() {
        assert!(
            NAMES.windows(2).all(|w| w[0] < w[1]),
            "catalog must be sorted"
        );
        for n in NAMES {
            assert!(
                crate::builtins::lookup(n).is_none(),
                "{n} is implemented and must not be in the catalog"
            );
            assert!(
                ppl_syntax::lexer::Keyword::from_upper(n).is_none(),
                "{n} is a keyword"
            );
        }
    }

    #[test]
    fn documented_commands_from_the_screenshot_are_present() {
        assert_eq!(lookup("SOLVE").unwrap().kind, CatalogKind::Command);
        assert_eq!(lookup("solve").unwrap().kind, CatalogKind::Cas);
        assert_eq!(lookup("append").unwrap().kind, CatalogKind::Cas);
        assert!(lookup("eval").is_some());
        assert!(lookup("NOT_A_PRIME_COMMAND").is_none());
        assert_eq!(lookup_case_insensitive("Solve").unwrap().name, "SOLVE");
    }
}
